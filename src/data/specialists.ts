export function getSpecialist(id?: string): Specialist | undefined {
  return SPECIALISTS.find((s) => s.id === id);
}

export function specialistsBy(filter: { specialty?: SpecialtyId; region?: string; service?: "online" | "offline"; q?: string }) {
  const q = filter.q?.trim().toLowerCase();
  return SPECIALISTS.filter(
    (s) =>
      (!filter.specialty || s.specialty === filter.specialty) &&
      (!filter.region || s.region === filter.region) &&
      (!filter.service || s.services.includes(filter.service)) &&
      (!q || s.name.toLowerCase().includes(q) || s.workplace.toLowerCase().includes(q) || s.approach.join(" ").toLowerCase().includes(q)),
  );
}

/** Mutaxassisning bo‘sh vaqtlari — kelgusi 7 kun uchun deterministik */
export function specialistSlots(id: string, fromKey: string = todayKey()): { date: string; times: string[] }[] {
  const all = ["09:00", "10:00", "11:00", "12:00", "14:00", "15:00", "16:00", "17:00", "18:00"];
  const out: { date: string; times: string[] }[] = [];
  for (let i = 0; i < 7; i++) {
    const date = addDays(fromKey, i);
    const rnd = mulberry32(hashString(`${id}|${date}`));
    const wd = weekdayOf(date);
    if (wd === 7) {
      out.push({ date, times: [] });
      continue;
    }
    const times = all.filter(() => rnd() > 0.55);
    out.push({ date, times: i === 0 ? times.filter((t) => t >= "15:00") : times });
  }
  return out;
}
