export function getExercise(id?: string): Exercise | undefined {
  return EXERCISES.find((e) => e.id === id);
}

export function exercisesBy(filter: { section?: Section; domain?: Domain; age?: number; aiOnly?: boolean; atHome?: boolean }) {
  return EXERCISES.filter(
    (e) =>
      (!filter.section || e.section === filter.section) &&
      (!filter.domain || e.domain === filter.domain) &&
      (filter.age === undefined || (filter.age >= e.ageMin - 1 && filter.age <= e.ageMax + 1)) &&
      (!filter.aiOnly || !!e.aiCheck) &&
      (!filter.atHome || e.atHome),
  );
}

/** Bo‘lim ichidagi mavzular ro‘yxati */
export function topicsOf(section: Section): string[] {
  return Array.from(new Set(EXERCISES.filter((e) => e.section === section).map((e) => e.topic)));
}
